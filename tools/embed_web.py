#!/usr/bin/env python3
"""Pack web/ into iUART/web_ui.h as gzip-compressed byte arrays served straight from flash.

Run after changing anything in web/:  python3 tools/embed_web.py
CI runs it with --check: the embedded files are unpacked and compared with web/
(byte-for-byte gzip output differs between zlib versions, the content must not).
"""
import gzip
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FILES = [("index.html", "INDEX_HTML"), ("style.css", "STYLE_CSS"), ("app.js", "APP_JS")]


def as_array(name: str, data: bytes) -> str:
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    body = ",\n  ".join(rows)
    return (f"static const uint8_t {name}_GZ[] PROGMEM = {{\n  {body}\n}};\n"
            f"static const size_t {name}_GZ_LEN = {len(data)};\n")


def check() -> int:
    header = (ROOT / "iUART" / "web_ui.h").read_text(encoding="utf-8")
    stale = []
    for file, name in FILES:
        m = re.search(rf"{name}_GZ\[\] PROGMEM = \{{(.*?)\}};", header, re.S)
        data = bytes(int(x, 16) for x in re.findall(r"0x([0-9a-f]{2})", m.group(1))) if m else b""
        if not m or gzip.decompress(data) != (ROOT / "web" / file).read_bytes():
            stale.append(file)
    if stale:
        print("iUART/web_ui.h is out of date for: " + ", ".join(stale) + " — run python3 tools/embed_web.py")
        return 1
    print("iUART/web_ui.h matches web/")
    return 0


def main() -> None:
    parts = ["// Generated by tools/embed_web.py from web/ — do not edit by hand.\n#pragma once\n#include <Arduino.h>\n"]
    for file, name in FILES:
        raw = (ROOT / "web" / file).read_bytes()
        # mtime=0 keeps the output identical between runs
        parts.append(as_array(name, gzip.compress(raw, compresslevel=9, mtime=0)))
    (ROOT / "iUART" / "web_ui.h").write_text("\n".join(parts), encoding="utf-8")
    print("wrote iUART/web_ui.h")


if __name__ == "__main__":
    sys.exit(check()) if "--check" in sys.argv else main()
